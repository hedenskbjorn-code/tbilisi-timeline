import { startServer, launch, openPage, waitReady } from "./helpers.mjs";
const server = await startServer(); const browser = await launch();
const page = await openPage(browser, `${server.url}/?e2e=1&idleload=1&base=off&nostats=1&lang=en#1990`);
const reqs = []; page.on("request", (r) => reqs.push(r.url().replace(server.url, "")));
page.on("console", (m) => { if (m.type() === "error") console.log("console error:", m.text().slice(0, 150)); });
await waitReady(page);
await page.waitForFunction(() => window.TT_E2E.map.getSource("places") && window.TT_E2E.map.getSource("mods") && window.TT_E2E.map.getSource("mons"), null, { timeout: 20000, polling: 500 }).catch((e) => console.log("WAIT FAILED"));
console.log(reqs.filter((u) => /places|modernism|sculptures|plaques/.test(u)));
console.log(await page.evaluate(() => ["places", "mods", "mons", "plqs"].map((s) => s + ":" + !!window.TT_E2E.map.getSource(s))));
await page.ctx.close(); await browser.close(); server.srv.close();
