import fs from "node:fs";
import path from "node:path";
import { startServer, launch, openPage, waitReady, DATA } from "./helpers.mjs";
const server = await startServer(); const browser = await launch();
const page = await openPage(browser, `${server.url}/?e2e=1&base=off&nostats=1&lang=en#1990`);
await waitReady(page);
const MOD = JSON.parse(fs.readFileSync(path.join(DATA, "modernism.json"), "utf8"));
await page.check("#showMod");
await page.waitForFunction(() => window.TT_E2E.map.getSource("mods"), null, { timeout: 20000 });
const c = MOD.items.find((x) => x.y <= 1990 && !x.ph);
const pt = await page.evaluate(([c, z]) => { const m = window.TT_E2E.map; m.jumpTo({ center: [c.lon, c.lat], zoom: z }); return new Promise((r) => m.once("idle", () => r(m.project([c.lon, c.lat])))); }, [c, 17]);
const box = await page.locator("#map canvas").first().boundingBox();
await page.mouse.click(box.x + pt.x, box.y + pt.y);
await page.waitForTimeout(1500);
console.log(c.id, await page.evaluate(() => [...document.querySelectorAll(".maplibregl-popup")].map((p) => p.innerText.slice(0, 120).replace(/\n/g, " | "))));
await page.ctx.close(); await browser.close(); server.srv.close();
